import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {plans,validateReviewedPlans,editorialRevisionCount} from '../content/assessments/expanded/reviewed.mjs';
import {REVIEWED_N5_ASSESSMENT_VERSION as version} from '../src/chapter-assessment.js';

export function buildReviewedMigration(){
 validateReviewedPlans();
 const plan=plans.map(p=>({chapter:p.chapter,expectedVersion:p.expectedVersion,forms:p.chapter===3?['A','B']:['A'],
  rows:p.rows.map((q,i)=>({id:q.id,sourceId:q.sourceId,form:q.assessment_meta.form,
   expectedMeta:Object.fromEntries([...new Set(['key','objective','itemType',...Object.keys(q.revision.meta).filter(k=>!['version','key','objectiveEvidence'].includes(k))])]
    .map(k=>[k,p.sourceRows[i].assessment_meta[k]??null])),revision:q.revision}))}));
 return `-- Generated by scripts/build-reviewed-n5-assessments.mjs.
-- Additive editorial revision. All historical banks and attempts stay intact.
-- Changed content is guarded; untouched live text, option images and voices copy.
CREATE TABLE IF NOT EXISTS n5_assessment_backup_217 (
 lesson_id uuid PRIMARY KEY, before_lesson jsonb NOT NULL,
 before_questions jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
DO $reviewed$
DECLARE plan jsonb := $plan$${JSON.stringify(plan,null,2)}$plan$::jsonb;
 b jsonb; r jsonb; choice jsonb; target uuid; course uuid; matches int; f jsonb;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:graph'));
 SELECT id INTO course FROM courses WHERE slug='n5';
 IF course IS NULL THEN RAISE EXCEPTION '217: N5 course missing'; END IF;
 PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:'||course));
 LOCK TABLE lessons,quiz_questions,quiz_options IN SHARE ROW EXCLUSIVE MODE;
 FOR b IN SELECT value FROM jsonb_array_elements(plan) LOOP
  SELECT count(*),(array_agg(l.id))[1] INTO matches,target
   FROM lessons l JOIN modules m ON m.id=l.module_id
   WHERE m.course_id=course AND m.slug='n5-b'||(b->>'chapter')
    AND l.type='quiz' AND l.slug LIKE 'assignment-bab-'||(b->>'chapter')||'-%';
  IF matches<>1 THEN RAISE EXCEPTION '217: missing/ambiguous source Bab %',b->>'chapter'; END IF;
  IF EXISTS(SELECT 1 FROM n5_assessment_backup_217 WHERE lesson_id=target) THEN CONTINUE; END IF;
  IF (SELECT assessment_policy->>'version' FROM lessons WHERE id=target) IS DISTINCT FROM b->>'expectedVersion'
   THEN RAISE EXCEPTION '217: source version changed Bab %',b->>'chapter'; END IF;
  IF (SELECT count(*) FROM quiz_questions WHERE lesson_id=target AND assessment_meta->>'version'=b->>'expectedVersion')<>jsonb_array_length(b->'rows')
   THEN RAISE EXCEPTION '217: source count changed Bab %',b->>'chapter'; END IF;
  FOR r IN SELECT value FROM jsonb_array_elements(b->'rows') LOOP
   IF NOT EXISTS(SELECT 1 FROM quiz_questions q WHERE q.id=(r->>'sourceId')::uuid AND q.lesson_id=target
    AND q.assessment_meta->>'version'=b->>'expectedVersion' AND q.assessment_meta->>'form'=r->>'form'
    AND NOT EXISTS(SELECT 1 FROM jsonb_each(r->'expectedMeta') expected(key,value)
     WHERE coalesce(q.assessment_meta->expected.key,'null'::jsonb) IS DISTINCT FROM expected.value))
    THEN RAISE EXCEPTION '217: source identity/objective changed Bab %',b->>'chapter'; END IF;
   IF NOT EXISTS(SELECT 1 FROM quiz_questions q WHERE q.id=(r->>'sourceId')::uuid AND to_jsonb(q) @> (r->'revision'->'expected'))
    THEN RAISE EXCEPTION '217: revised source content changed Bab %, question %',b->>'chapter',r->>'sourceId'; END IF;
   IF r->'revision' ? 'expectedOptions' AND
    (SELECT jsonb_agg(jsonb_build_object('id',o.id,'option_text',o.option_text,'is_correct',o.is_correct,'sort_order',o.sort_order,'image_url',o.image_url) ORDER BY o.sort_order,o.id)
      FROM quiz_options o WHERE o.question_id=(r->>'sourceId')::uuid) IS DISTINCT FROM r->'revision'->'expectedOptions'
    THEN RAISE EXCEPTION '217: revised source choices changed Bab %, question %',b->>'chapter',r->>'sourceId'; END IF;
  END LOOP;
  IF (SELECT jsonb_typeof(assessment_policy->'objectives') FROM lessons WHERE id=target) IS DISTINCT FROM 'array'
   THEN RAISE EXCEPTION '217: missing objectives Bab %',b->>'chapter'; END IF;
  IF (SELECT count(*)=0 OR count(*)<>count(DISTINCT objective->>'id') OR count(*) FILTER(WHERE nullif(objective->>'id','') IS NULL)>0
   FROM lessons l CROSS JOIN LATERAL jsonb_array_elements(l.assessment_policy->'objectives') objective WHERE l.id=target)
   THEN RAISE EXCEPTION '217: invalid objectives Bab %',b->>'chapter'; END IF;
 END LOOP;
 FOR b IN SELECT value FROM jsonb_array_elements(plan) LOOP
  SELECT l.id INTO target FROM lessons l JOIN modules m ON m.id=l.module_id
   WHERE m.course_id=course AND m.slug='n5-b'||(b->>'chapter') AND l.type='quiz'
    AND l.slug LIKE 'assignment-bab-'||(b->>'chapter')||'-%';
  IF EXISTS(SELECT 1 FROM n5_assessment_backup_217 WHERE lesson_id=target) THEN CONTINUE; END IF;
  INSERT INTO n5_assessment_backup_217(lesson_id,before_lesson,before_questions)
   SELECT l.id,to_jsonb(l),coalesce((SELECT jsonb_agg(to_jsonb(q)||jsonb_build_object('options',
    (SELECT jsonb_agg(to_jsonb(o) ORDER BY o.sort_order,o.id) FROM quiz_options o WHERE o.question_id=q.id)) ORDER BY q.id)
    FROM quiz_questions q WHERE q.lesson_id=l.id AND q.assessment_meta->>'version'=b->>'expectedVersion'),'[]'::jsonb)
   FROM lessons l WHERE l.id=target;
  FOR r IN SELECT value FROM jsonb_array_elements(b->'rows') LOOP
   f:=r->'revision'->'fields';
   INSERT INTO quiz_questions(id,lesson_id,question,question_type,question_category,grammar_id,
    section_number,section_label,section_instruction,audio_script,audio_scene,passage,image_url,correct_answer,explanation,sort_order,assessment_meta)
   SELECT (r->>'id')::uuid,target,
    CASE WHEN f ? 'question' THEN f->>'question' ELSE q.question END,q.question_type,q.question_category,q.grammar_id,
    CASE WHEN f ? 'section_number' THEN (f->>'section_number')::int ELSE q.section_number END,
    CASE WHEN f ? 'section_label' THEN f->>'section_label' ELSE q.section_label END,
    CASE WHEN f ? 'section_instruction' THEN f->>'section_instruction' ELSE q.section_instruction END,
    CASE WHEN f ? 'audio_script' THEN f->>'audio_script' ELSE q.audio_script END,q.audio_scene,
    CASE WHEN f ? 'passage' THEN f->>'passage' ELSE q.passage END,
    CASE WHEN f ? 'image_url' THEN f->>'image_url' ELSE q.image_url END,q.correct_answer,
    CASE WHEN f ? 'explanation' THEN f->>'explanation' ELSE q.explanation END,q.sort_order,
    q.assessment_meta||(r->'revision'->'meta')
   FROM quiz_questions q WHERE q.id=(r->>'sourceId')::uuid;
   IF r->'revision' ? 'options' THEN
    FOR choice IN SELECT value FROM jsonb_array_elements(r->'revision'->'options') LOOP
     INSERT INTO quiz_options(id,question_id,option_text,is_correct,sort_order)
      VALUES((choice->>'id')::uuid,(r->>'id')::uuid,choice->>'option_text',(choice->>'is_correct')::boolean,(choice->>'sort_order')::int);
    END LOOP;
   ELSE
    INSERT INTO quiz_options(id,question_id,option_text,is_correct,image_url,sort_order)
     SELECT md5(id::text||':${version}')::uuid,(r->>'id')::uuid,option_text,is_correct,image_url,sort_order
      FROM quiz_options WHERE question_id=(r->>'sourceId')::uuid;
   END IF;
  END LOOP;
  IF EXISTS(SELECT 1 FROM quiz_questions q WHERE lesson_id=target AND assessment_meta->>'version'='${version}'
   AND ((SELECT count(*) FROM quiz_options o WHERE o.question_id=q.id)<>CASE WHEN q.assessment_meta->>'itemType' IN ('verbal_expression','quick_response') THEN 3 ELSE 4 END
    OR (SELECT count(*) FROM quiz_options o WHERE o.question_id=q.id AND is_correct)<>1
    OR (SELECT count(DISTINCT option_text) FROM quiz_options o WHERE o.question_id=q.id)<>(SELECT count(*) FROM quiz_options o WHERE o.question_id=q.id)))
   THEN RAISE EXCEPTION '217: invalid choices Bab %',b->>'chapter'; END IF;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements_text(b->'forms') AS forms(form) WHERE
    (SELECT count(*) FROM quiz_questions q WHERE lesson_id=target AND assessment_meta->>'version'='${version}' AND assessment_meta->>'form'=forms.form)<>36
    OR (SELECT count(*) FROM quiz_questions q WHERE lesson_id=target AND assessment_meta->>'version'='${version}' AND assessment_meta->>'form'=forms.form AND question_category='vocabulary')<>11
    OR (SELECT count(*) FROM quiz_questions q WHERE lesson_id=target AND assessment_meta->>'version'='${version}' AND assessment_meta->>'form'=forms.form AND question_category='grammar')<>9
    OR (SELECT count(*) FROM quiz_questions q WHERE lesson_id=target AND assessment_meta->>'version'='${version}' AND assessment_meta->>'form'=forms.form AND question_category='reading')<>3
    OR (SELECT count(*) FROM quiz_questions q WHERE lesson_id=target AND assessment_meta->>'version'='${version}' AND assessment_meta->>'form'=forms.form AND question_category='listening')<>13)
   THEN RAISE EXCEPTION '217: invalid blueprint Bab %',b->>'chapter'; END IF;
  IF EXISTS(SELECT 1 FROM quiz_questions q WHERE lesson_id=target AND assessment_meta->>'version'='${version}'
   AND NOT EXISTS(SELECT 1 FROM lessons l CROSS JOIN LATERAL jsonb_array_elements(l.assessment_policy->'objectives') objective
    WHERE l.id=target AND objective->>'id'=q.assessment_meta->>'objective'))
   OR EXISTS(SELECT 1 FROM lessons l CROSS JOIN LATERAL jsonb_array_elements(l.assessment_policy->'objectives') objective
    CROSS JOIN jsonb_array_elements_text(b->'forms') AS forms(form) WHERE l.id=target
    AND (SELECT count(*) FROM quiz_questions q WHERE q.lesson_id=target AND q.assessment_meta->>'version'='${version}'
     AND q.assessment_meta->>'form'=forms.form AND q.assessment_meta->>'objective'=objective->>'id'
     AND q.assessment_meta->'objectiveEvidence'='true'::jsonb)<greatest(2,coalesce((l.assessment_policy->>'minimumObjectiveCorrect')::int,1)))
   THEN RAISE EXCEPTION '217: objective evidence coverage changed Bab %',b->>'chapter'; END IF;
  UPDATE lessons SET assessment_policy=assessment_policy||'{"version":"${version}"}'::jsonb,updated_at=now() WHERE id=target;
  RAISE NOTICE '217: N5 source Bab % reviewed: 36 per packet; direct objective evidence verified',b->>'chapter';
 END LOOP;
END;
$reviewed$;
`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const path=new URL('../migrations/217_review_n5_assignment_quality.sql',import.meta.url),sql=buildReviewedMigration();
 if(process.argv.includes('--check')){if((await readFile(path,'utf8')).replaceAll('\r\n','\n')!==sql)throw Error('Generated migration drift');}
 else await writeFile(path,sql);
 console.log(`${plans.length} reviewed assignments; ${editorialRevisionCount} editorial item revisions; 684 versioned rows.`);
}
