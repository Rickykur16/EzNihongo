// Generate the deployable content migration from the editable N5 story catalog.
// node backend/scripts/build-n5-kanji-mnemonics.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';

const catalogUrl = new URL('../content/n5-support/kanji-mnemonics.json', import.meta.url);
const migrationUrl = new URL('../migrations/212_n5_visual_mnemonics.sql', import.meta.url);
const catalog = JSON.parse(await readFile(catalogUrl, 'utf8'));
const quote = value => `'${value.replaceAll("'", "''")}'`;
const seen = new Set();
for (const { character, meaning, mnemonic } of catalog) {
  if (!/^\p{Unified_Ideograph}$/u.test(character) || seen.has(character)) {
    throw new Error(`Invalid or duplicate kanji: ${character}`);
  }
  if (!meaning?.trim() || !mnemonic?.startsWith('Bayangkan ') || mnemonic.length > 320) {
    throw new Error(`Invalid or overlong mnemonic: ${character}`);
  }
  seen.add(character);
}
const values = catalog.map(({ character, mnemonic }) =>
  `    (${quote(character)}, ${quote(mnemonic)})`).join(',\n');
const sql = `-- Generated by backend/scripts/build-n5-kanji-mnemonics.mjs; edit the JSON catalog.
-- Visual memory stories for the existing 103 N5 course kanji, not etymologies.
-- All existing N5-course copies are updated, including empty and imported stories.
-- Card identity, lesson ownership, readings, meanings and compounds stay intact.
-- The first previous value is retained per card, including NULL and empty strings.
-- Migration runner wraps this file in a transaction. No new kanji cards are added.

CREATE TABLE IF NOT EXISTS n5_kanji_mnemonic_backup_212 (
  kanji_id UUID PRIMARY KEY,
  mnemonic TEXT,
  backed_up_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $mnemonics$
DECLARE changed INT;
BEGIN
  -- Keep backup and replacement consistent with concurrent admin edits.
  LOCK TABLE kanji_items IN SHARE ROW EXCLUSIVE MODE;
  CREATE TEMP TABLE _n5_mnemonics_212 (
    character TEXT PRIMARY KEY,
    mnemonic TEXT NOT NULL
  ) ON COMMIT DROP;
  INSERT INTO _n5_mnemonics_212 (character, mnemonic) VALUES
${values};

  INSERT INTO n5_kanji_mnemonic_backup_212 (kanji_id, mnemonic)
  SELECT k.id, k.mnemonic
    FROM kanji_items k
    JOIN lessons l ON l.id = k.lesson_id
    JOIN modules m ON m.id = l.module_id
    JOIN courses c ON c.id = m.course_id
    JOIN _n5_mnemonics_212 n ON n.character = k.character
   WHERE c.slug = 'n5' AND k.jlpt_level = 'N5'
     AND k.mnemonic IS DISTINCT FROM n.mnemonic
  ON CONFLICT (kanji_id) DO NOTHING;

  UPDATE kanji_items k
     SET mnemonic = n.mnemonic, updated_at = NOW()
    FROM _n5_mnemonics_212 n, lessons l, modules m, courses c
   WHERE k.character = n.character
     AND l.id = k.lesson_id AND m.id = l.module_id AND c.id = m.course_id
     AND c.slug = 'n5' AND k.jlpt_level = 'N5'
     AND k.mnemonic IS DISTINCT FROM n.mnemonic;
  GET DIAGNOSTICS changed = ROW_COUNT;
  RAISE NOTICE '212: updated % N5 kanji mnemonic rows; previous values backed up', changed;
  DROP TABLE _n5_mnemonics_212;
END $mnemonics$;
`;

if (process.argv.includes('--check')) {
  if (await readFile(migrationUrl, 'utf8') !== sql) {
    throw new Error('N5 mnemonic migration is stale; run this script without --check.');
  }
  console.log(`N5 mnemonic migration matches all ${catalog.length} stories.`);
} else {
  await writeFile(migrationUrl, sql, 'utf8');
  console.log(`Generated migration with ${catalog.length} N5 stories.`);
}
