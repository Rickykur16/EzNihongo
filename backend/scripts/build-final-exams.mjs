import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {banks,validateFinalBank} from '../content/final-exams/index.mjs';
import {assertChapterForm} from '../src/chapter-assessment.js';
export {banks};
export function buildFinalExamSql(){
 for(const b of banks)assertChapterForm(b.policy,validateFinalBank(b));
 return `-- Generated by backend/scripts/build-final-exams.mjs. Additive; original EzNihongo content.
-- Migration runner wraps this statement in a transaction. Existing course material and attempts are untouched.
DO $final$
DECLARE payload jsonb := $bank$${JSON.stringify(banks)}$bank$::jsonb;
 b jsonb; q jsonb; o jsonb; course_uuid uuid; module_order int; existing_count int;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:graph'));
 LOCK TABLE courses,modules,lessons,quiz_questions,quiz_options IN SHARE ROW EXCLUSIVE MODE;
 -- Preflight both courses before writing either bank.
 FOR b IN SELECT value FROM jsonb_array_elements(payload) LOOP
  SELECT count(*) INTO existing_count FROM courses WHERE slug=b->>'level';
  IF existing_count<>1 THEN RAISE EXCEPTION '194 missing/ambiguous course: %',b->>'level'; END IF;
  IF EXISTS(SELECT 1 FROM modules m JOIN courses c ON c.id=m.course_id WHERE c.slug=b->>'level' AND m.slug=b->>'moduleSlug' AND m.id<>(b->>'moduleId')::uuid)
   THEN RAISE EXCEPTION '194 final module slug already used: %',b->>'level'; END IF;
  IF EXISTS(SELECT 1 FROM lessons WHERE id=(b->>'lessonId')::uuid) THEN
   IF NOT EXISTS(SELECT 1 FROM lessons l JOIN modules m ON m.id=l.module_id JOIN courses c ON c.id=m.course_id
     WHERE l.id=(b->>'lessonId')::uuid AND l.slug=b->>'lessonSlug' AND l.type='quiz'
       AND m.id=(b->>'moduleId')::uuid AND m.slug=b->>'moduleSlug' AND c.slug=b->>'level'
       AND l.assessment_policy->>'version'=b->>'version')
    THEN RAISE EXCEPTION '194 conflicting final exam: %',b->>'level'; END IF;
   SELECT count(*) INTO existing_count FROM quiz_questions WHERE lesson_id=(b->>'lessonId')::uuid AND assessment_meta->>'version'=b->>'version';
   IF existing_count<>jsonb_array_length(b->'rows') THEN RAISE EXCEPTION '194 incomplete existing bank'; END IF;
   IF EXISTS(SELECT 1 FROM jsonb_array_elements(b->'rows') x WHERE NOT EXISTS(SELECT 1 FROM quiz_questions q WHERE q.id=(x->>'id')::uuid AND q.lesson_id=(b->>'lessonId')::uuid))
    THEN RAISE EXCEPTION '194 existing question identity changed'; END IF;
  ELSIF EXISTS(SELECT 1 FROM modules WHERE id=(b->>'moduleId')::uuid) THEN
   RAISE EXCEPTION '194 conflicting module identity';
  END IF;
 END LOOP;
 FOR b IN SELECT value FROM jsonb_array_elements(payload) LOOP
  -- Preserve later teacher edits on replay rather than overwriting their bank.
  IF EXISTS(SELECT 1 FROM lessons WHERE id=(b->>'lessonId')::uuid) THEN CONTINUE; END IF;
  SELECT id INTO course_uuid FROM courses WHERE slug=b->>'level';
  PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:'||course_uuid::text));
  SELECT coalesce(max(sort_order),0)+1 INTO module_order FROM modules WHERE course_id=course_uuid;
  INSERT INTO modules(id,course_id,slug,title,description,sort_order,section_name,quiz_spec)
   VALUES((b->>'moduleId')::uuid,course_uuid,b->>'moduleSlug',b->>'title',b->>'content',module_order,'Final Exam',jsonb_build_object('total',jsonb_array_length(b->'rows'),'version',b->>'version'));
  INSERT INTO lessons(id,module_id,slug,title,type,content,sort_order,passing_score_pct,questions_per_attempt,assessment_policy,cooldown_hours)
   VALUES((b->>'lessonId')::uuid,(b->>'moduleId')::uuid,b->>'lessonSlug',b->>'title','quiz',b->>'content',1,70,jsonb_array_length(b->'rows'),b->'policy',12);
  FOR q IN SELECT value FROM jsonb_array_elements(b->'rows') LOOP
   INSERT INTO quiz_questions(id,lesson_id,question,question_type,question_category,section_number,section_label,section_instruction,passage,audio_script,image_url,explanation,sort_order,assessment_meta)
    VALUES((q->>'id')::uuid,(b->>'lessonId')::uuid,q->>'question',q->>'question_type',q->>'question_category',(q->>'section_number')::int,q->>'section_label',q->>'section_instruction',q->>'passage',q->>'audio_script',q->>'image_url',q->>'explanation',(q->>'sort_order')::int,q->'assessment_meta');
   FOR o IN SELECT value FROM jsonb_array_elements(q->'options') LOOP
    INSERT INTO quiz_options(id,question_id,option_text,is_correct,sort_order)
     VALUES((o->>'id')::uuid,(q->>'id')::uuid,o->>'option_text',(o->>'is_correct')::boolean,(o->>'sort_order')::int);
   END LOOP;
  END LOOP;
 END LOOP;
END $final$;
`;
}

