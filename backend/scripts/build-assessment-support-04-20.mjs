import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {banks, bankRows, supportEdits} from '../content/assessments/support/n5-04-20.mjs';
import {banks as published} from '../content/assessments/jlpt/revised.mjs';
export {banks, supportEdits};
const lit = value => `'${String(value).replaceAll("'", "''")}'`;
const json = value => `${lit(JSON.stringify(value))}::jsonb`;

export function buildSupportMigration() {
  let sql = `-- Generated by build-assessment-support-04-20.mjs; reviewed support content only.
-- Active v4 question IDs/keys/options and existing attempt snapshots remain unchanged.
-- Unexpected edits to a targeted field require review; unrelated owner edits are preserved.
CREATE TABLE IF NOT EXISTS n5_assessment_support_backup_185 (
  lesson_id uuid PRIMARY KEY, before_lesson jsonb NOT NULL,
  before_questions jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
`;
  for (const bank of banks) {
    const old = published.find(b => b.chapter === bank.chapter);
    const rows = bankRows(bank);
    const edits = supportEdits.filter(e => e.chapter === bank.chapter).map(e => ({...e, row: rows[e.number - 1], column: e.field === 'prompt' ? 'question' : 'passage'}));
    const ids = edits.map(e => lit(e.row.id)).join(',');
    const predicate = ids ? `q.id IN (${ids})` : 'false';
    sql += `
DO $support$
DECLARE target uuid; matches int;
BEGIN
 SELECT count(*),(array_agg(l.id))[1] INTO matches,target
 FROM lessons l JOIN modules m ON m.id=l.module_id JOIN courses c ON c.id=m.course_id
 WHERE c.slug='n5' AND m.slug='n5-b${bank.chapter}' AND l.type='quiz'
 AND l.slug LIKE 'assignment-bab-${bank.chapter}-%';
 IF matches<>1 THEN RAISE EXCEPTION '185: missing/ambiguous Bab ${bank.chapter} assignment'; END IF;
 PERFORM 1 FROM lessons WHERE id=target FOR UPDATE;
 IF EXISTS(SELECT 1 FROM n5_assessment_support_backup_185 WHERE lesson_id=target) THEN RETURN; END IF;
 IF (SELECT assessment_policy->>'version' FROM lessons WHERE id=target) IS DISTINCT FROM 'n5-assessment-v4'
 THEN RAISE EXCEPTION '185: expected v4 Bab ${bank.chapter}'; END IF;
 IF (SELECT count(*) FROM quiz_questions WHERE lesson_id=target AND assessment_meta->>'version'='n5-assessment-v4')<>24
 THEN RAISE EXCEPTION '185: expected 24 active questions Bab ${bank.chapter}'; END IF;
 IF (SELECT (assessment_policy->'transferTask')-'exampleDialogue' FROM lessons WHERE id=target) IS DISTINCT FROM ${json(old.transferTask)}
 THEN RAISE EXCEPTION '185: review owner transfer-task edit Bab ${bank.chapter} before applying'; END IF;
`;
    for (const edit of edits) {
      sql += ` PERFORM 1 FROM quiz_questions WHERE id=${lit(edit.row.id)} AND lesson_id=target FOR UPDATE;
 IF NOT EXISTS(SELECT 1 FROM quiz_questions WHERE id=${lit(edit.row.id)} AND lesson_id=target
 AND assessment_meta->>'version'='n5-assessment-v4' AND assessment_meta->>'key'=${lit(edit.row.assessment_meta.key)}
 AND ${edit.column}=${lit(edit.before)})
 THEN RAISE EXCEPTION '185: missing or changed source ${edit.row.assessment_meta.key}; review before applying'; END IF;
`;
    }
    sql += ` INSERT INTO n5_assessment_support_backup_185(lesson_id,before_lesson,before_questions)
 SELECT l.id,to_jsonb(l),COALESCE((SELECT jsonb_agg(to_jsonb(q) || jsonb_build_object('options',
   (SELECT COALESCE(jsonb_agg(to_jsonb(o) ORDER BY o.sort_order,o.id),'[]'::jsonb) FROM quiz_options o WHERE o.question_id=q.id)) ORDER BY q.id)
   FROM quiz_questions q WHERE q.lesson_id=target AND ${predicate}),'[]'::jsonb)
 FROM lessons l WHERE l.id=target;
`;
    for (const edit of edits) sql += ` UPDATE quiz_questions SET ${edit.column}=${lit(edit.value)} WHERE id=${lit(edit.row.id)} AND lesson_id=target;
`;
    sql += ` UPDATE lessons SET assessment_policy=jsonb_set(assessment_policy,'{transferTask}',(assessment_policy->'transferTask') || ${json(bank.transferTask)},true),updated_at=now() WHERE id=target;
END;
$support$;
`;
  }
  return sql;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const destination = new URL('../migrations/185_n5_assessment_support_04_20.sql', import.meta.url);
  const content = buildSupportMigration();
  if (process.argv.includes('--check')) {
    if ((await readFile(destination, 'utf8')).replaceAll('\r\n', '\n') !== content) throw Error('Regenerate migration 185');
  } else await writeFile(destination, content);
  console.log(`Validated ${banks.length} transfer tasks and ${supportEdits.length} source-field corrections; active v4 IDs and scoring unchanged.`);
}
