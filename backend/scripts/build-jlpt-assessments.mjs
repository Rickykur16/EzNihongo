const lit=v=>v==null?'NULL':`'${String(v).replaceAll("'","''")}'`;
const json=v=>`${lit(JSON.stringify(v))}::jsonb`;
export function buildRollout(){
  let sql=`-- Generated by build-jlpt-assessments.mjs. New v3 IDs preserve all v2 questions and snapshots.
CREATE TABLE IF NOT EXISTS n5_assessment_backup_172(lesson_id uuid PRIMARY KEY,before_data jsonb NOT NULL,created_at timestamptz NOT NULL DEFAULT now());
`;
  for(const bank of banks){
    const {forms,...policy}=bank;
    sql+=`\nDO $jlpt$
DECLARE target uuid; matches int; scene jsonb;
BEGIN
 SELECT count(*),(array_agg(l.id))[1] INTO matches,target FROM lessons l
 JOIN modules m ON m.id=l.module_id JOIN courses c ON c.id=m.course_id
 WHERE c.slug='n5' AND l.type='quiz' AND l.slug LIKE 'assignment-bab-${bank.chapter}-%'
 AND m.title ~* '^BAB\\s*${bank.chapter}\\s*[:：]';
 IF matches<>1 THEN RAISE EXCEPTION '172: missing/ambiguous Bab ${bank.chapter} assignment'; END IF;
 IF EXISTS(SELECT 1 FROM n5_assessment_backup_172 WHERE lesson_id=target) THEN RETURN; END IF;
 IF (SELECT assessment_policy->>'version' FROM lessons WHERE id=target) IS DISTINCT FROM 'n5-assessment-v2'
 THEN RAISE EXCEPTION '172: expected v2 bank for Bab ${bank.chapter}'; END IF;
 INSERT INTO n5_assessment_backup_172(lesson_id,before_data)
 SELECT id,jsonb_build_object('assessment_policy',assessment_policy,'content',content,'questions_per_attempt',questions_per_attempt) FROM lessons WHERE id=target;
`;
    for(const row of validateBank(bank)){
      if(row.audio_script) sql+=` -- Preserve the admin's corresponding A/B voice assignment, not the old script.
 SELECT audio_scene INTO scene FROM quiz_questions WHERE lesson_id=target AND assessment_meta->>'version'='n5-assessment-v2'
 AND question_category='listening' AND sort_order=${row.sort_order} ORDER BY id LIMIT 1;
`;
      const fields=Object.keys(row).filter(k=>k!=='options');
      sql+=` INSERT INTO quiz_questions(lesson_id,${fields.join(',')},audio_scene) VALUES(target,${fields.map(k=>k==='assessment_meta'?json(row[k]):typeof row[k]==='number'?row[k]:lit(row[k])).join(',')},${row.audio_script?'scene':'NULL'});\n`;
      for(const o of row.options)sql+=` INSERT INTO quiz_options(id,question_id,option_text,is_correct,sort_order) VALUES(${lit(o.id)},${lit(row.id)},${lit(o.option_text)},${o.is_correct},${o.sort_order});\n`;
    }
    const content='24 soal persiapan JLPT N5 sesuai materi sampai bab ini. Seluruh soal tampil: 6 aksara/kosakata, 10 tata bahasa, 4 membaca, 4 listening. Termasuk susunan ★ dan pilihan listening yang dibacakan. Audio boleh diputar ulang untuk latihan. Petunjuk Indonesia dikurangi bertahap. Pembahasan dan transkrip muncul setelah submit. Nilai lulus kelas 70%, tiap kategori minimal 50%, dan minimal satu jawaban benar per tujuan; ini bukan skala nilai resmi JLPT.';
    sql+=` UPDATE lessons SET assessment_policy=${json(policy)},content=${lit(content)},questions_per_attempt=24,updated_at=now() WHERE id=target;
END;
$jlpt$;
`;
  }
  return sql;
}

