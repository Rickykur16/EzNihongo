import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {scoredBanks} from '../content/final-exams/scoring.mjs';
import {namedBanks} from '../content/final-exams/names.mjs';
const fields=['question','audio_script','image_url','explanation','assessment_meta','options'];
const select=q=>Object.fromEntries(fields.map(k=>[k,q[k]]));
export function buildNamesSql(){
 const edits=namedBanks.flatMap((bank,i)=>bank.rows.flatMap((q,j)=>JSON.stringify(q)===JSON.stringify(scoredBanks[i].rows[j])?[]:[{id:q.id,lessonId:bank.lessonId,old:select(scoredBanks[i].rows[j]),next:select(q)}]));
 return `-- Generated by backend/scripts/build-final-exam-names.mjs.
-- Only current bank wording changes. Immutable attempts and old artwork remain intact.
DO $names$
DECLARE edits jsonb := $payload$${JSON.stringify(edits)}$payload$::jsonb; e jsonb; o jsonb; current_row jsonb;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:graph'));
 LOCK TABLE quiz_questions,quiz_options IN SHARE ROW EXCLUSIVE MODE;
 FOR e IN SELECT value FROM jsonb_array_elements(edits) LOOP
  SELECT jsonb_build_object('question',question,'audio_script',audio_script,'image_url',image_url,'explanation',explanation,'assessment_meta',assessment_meta,'options',(SELECT jsonb_agg(jsonb_build_object('id',o.id,'option_text',o.option_text,'is_correct',o.is_correct,'sort_order',o.sort_order) ORDER BY o.sort_order) FROM quiz_options o WHERE o.question_id=quiz_questions.id))
  INTO current_row FROM quiz_questions WHERE id=(e->>'id')::uuid AND lesson_id=(e->>'lessonId')::uuid;
  IF current_row IS NULL THEN RAISE EXCEPTION '197 missing question %',e->>'id'; END IF;
  IF current_row->'assessment_meta'->>'wordingVersion'='natural-names-v1' THEN CONTINUE; END IF;
  IF current_row IS DISTINCT FROM e->'old' THEN RAISE EXCEPTION '197 question edited; review required %',e->>'id'; END IF;
 END LOOP;
 FOR e IN SELECT value FROM jsonb_array_elements(edits) LOOP
  IF EXISTS(SELECT 1 FROM quiz_questions WHERE id=(e->>'id')::uuid AND assessment_meta->>'wordingVersion'='natural-names-v1') THEN CONTINUE; END IF;
  FOR o IN SELECT value FROM jsonb_array_elements(e->'next'->'options') LOOP
   UPDATE quiz_options SET option_text=o->>'option_text' WHERE id=(o->>'id')::uuid AND question_id=(e->>'id')::uuid;
  END LOOP;
  UPDATE quiz_questions SET question=e->'next'->>'question',audio_script=e->'next'->>'audio_script',image_url=e->'next'->>'image_url',explanation=e->'next'->>'explanation',assessment_meta=e->'next'->'assessment_meta'
  WHERE id=(e->>'id')::uuid AND assessment_meta->>'wordingVersion' IS DISTINCT FROM 'natural-names-v1';
 END LOOP;
END $names$;
`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const target=new URL('../migrations/197_final_exam_natural_names.sql',import.meta.url),sql=buildNamesSql();
 if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8').replaceAll('\r\n','\n')!==sql)throw Error('Names migration drift');}
 else fs.writeFileSync(target,sql);
 const assets=new Set(namedBanks.flatMap(b=>b.rows.filter(q=>q.image_url).map(q=>q.image_url)));
 for(const asset of assets){const file=new URL('../..'+asset,import.meta.url),old=new URL(file.href.replace('-names-v1.svg','.svg'));
 const svg=fs.readFileSync(old,'utf8').replaceAll('Aさん','あやさん').replace('>A</text>','>あや</text>').replace('<text x="518" y="105" font-size="27">B</text>','');
 if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==svg)throw Error('Named artwork drift');}else fs.writeFileSync(file,svg);
 }
 console.log('Natural names: '+namedBanks.reduce((n,b)=>n+b.rows.filter(q=>q.question_category==='listening').length,0)+' listening entries');
}
