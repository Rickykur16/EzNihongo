import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {scoredBanks} from '../content/final-exams/scoring.mjs';
export function buildScoringSql() {
 const payload=scoredBanks.map(({level,version,lessonId,moduleId,policy,content})=>({level,version,lessonId,moduleId,policy,content}));
 return `-- Generated by backend/scripts/build-final-exam-scoring.mjs.
-- Apply only to future attempts; completed results and pending snapshots stay immutable.
DO $scoring$
DECLARE payload jsonb := $policy$${JSON.stringify(payload)}$policy$::jsonb;
 b jsonb; current_policy jsonb;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:graph'));
 LOCK TABLE modules,lessons IN SHARE ROW EXCLUSIVE MODE;
 FOR b IN SELECT value FROM jsonb_array_elements(payload) LOOP
  SELECT l.assessment_policy INTO current_policy FROM lessons l
   JOIN modules m ON m.id=l.module_id JOIN courses c ON c.id=m.course_id
   WHERE l.id=(b->>'lessonId')::uuid AND m.id=(b->>'moduleId')::uuid AND c.slug=b->>'level' AND l.type='quiz';
  IF current_policy IS NULL OR (current_policy->>'version') IS DISTINCT FROM (b->>'version')
   OR (current_policy->>'scoringVersion' IS NOT NULL AND current_policy->>'scoringVersion'<>b->'policy'->>'scoringVersion')
   THEN RAISE EXCEPTION '196 missing/conflicting final exam: %',b->>'level'; END IF;
 END LOOP;
 FOR b IN SELECT value FROM jsonb_array_elements(payload) LOOP
  -- Preserve teacher edits on replay.
  IF EXISTS(SELECT 1 FROM lessons WHERE id=(b->>'lessonId')::uuid AND assessment_policy->>'scoringVersion'=b->'policy'->>'scoringVersion') THEN CONTINUE; END IF;
  UPDATE lessons SET assessment_policy=assessment_policy||b->'policy',content=b->>'content'
   WHERE id=(b->>'lessonId')::uuid;
  UPDATE modules SET description=b->>'content' WHERE id=(b->>'moduleId')::uuid;
 END LOOP;
END $scoring$;
`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)) {
 const file=new URL('../migrations/196_final_exam_jlpt_scoring.sql',import.meta.url),sql=buildScoringSql();
 if(process.argv.includes('--check')) {if(fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')!==sql)throw Error('Scoring migration drift');}
 else fs.writeFileSync(file,sql);
 console.log('JLPT estimated scoring: N5 80/180, N4 90/180; sections 38/120 + 19/60');
}
