import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {rotationBanks,validateRotationBank} from '../content/final-exams/rotation.mjs';
export function buildRotationSql() {
 rotationBanks.forEach(validateRotationBank);
 return `-- Generated by backend/scripts/build-final-exam-rotation.mjs.
-- Add v2 A/B packages; keep v1 questions, answer IDs and all attempt snapshots.
DO $rotation$
DECLARE payload jsonb := $bank$${JSON.stringify(rotationBanks)}$bank$::jsonb;
 b jsonb; q jsonb; o jsonb; active_version text; existing_count int;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:graph'));
 LOCK TABLE courses,modules,lessons,quiz_questions,quiz_options IN SHARE ROW EXCLUSIVE MODE;
 -- Validate both targets and every identity before updating either course.
 FOR b IN SELECT value FROM jsonb_array_elements(payload) LOOP
  SELECT l.assessment_policy->>'version' INTO active_version
   FROM lessons l JOIN modules m ON m.id=l.module_id JOIN courses c ON c.id=m.course_id
   WHERE l.id=(b->>'lessonId')::uuid AND l.slug=b->>'lessonSlug' AND l.type='quiz'
    AND m.id=(b->>'moduleId')::uuid AND m.slug=b->>'moduleSlug' AND c.slug=b->>'level';
  IF active_version IS NULL OR active_version NOT IN ('jlpt-final-'||(b->>'level')||'-v1',b->>'version')
   THEN RAISE EXCEPTION '195 missing/conflicting final exam: %',b->>'level'; END IF;
  SELECT count(*) INTO existing_count FROM quiz_questions
   WHERE lesson_id=(b->>'lessonId')::uuid AND assessment_meta->>'version'=b->>'version';
  IF active_version=b->>'version' THEN
   IF existing_count<>jsonb_array_length(b->'rows') OR EXISTS(
    SELECT 1 FROM jsonb_array_elements(b->'rows') x WHERE NOT EXISTS(
     SELECT 1 FROM quiz_questions q WHERE q.id=(x->>'id')::uuid AND q.lesson_id=(b->>'lessonId')::uuid AND q.assessment_meta->>'version'=b->>'version'))
    THEN RAISE EXCEPTION '195 incomplete existing packages'; END IF;
  ELSIF existing_count<>0 OR EXISTS(SELECT 1 FROM quiz_questions WHERE id IN(SELECT (x->>'id')::uuid FROM jsonb_array_elements(b->'rows') x))
   OR EXISTS(SELECT 1 FROM quiz_options WHERE id IN(SELECT (y->>'id')::uuid FROM jsonb_array_elements(b->'rows') x CROSS JOIN LATERAL jsonb_array_elements(x->'options') y))
   THEN RAISE EXCEPTION '195 conflicting package identity';
  END IF;
 END LOOP;
 FOR b IN SELECT value FROM jsonb_array_elements(payload) LOOP
  -- Replay preserves subsequent teacher edits.
  IF EXISTS(SELECT 1 FROM lessons WHERE id=(b->>'lessonId')::uuid AND assessment_policy->>'version'=b->>'version') THEN CONTINUE; END IF;
  FOR q IN SELECT value FROM jsonb_array_elements(b->'rows') LOOP
   INSERT INTO quiz_questions(id,lesson_id,question,question_type,question_category,section_number,section_label,section_instruction,passage,audio_script,image_url,explanation,sort_order,assessment_meta)
    VALUES((q->>'id')::uuid,(b->>'lessonId')::uuid,q->>'question',q->>'question_type',q->>'question_category',(q->>'section_number')::int,q->>'section_label',q->>'section_instruction',q->>'passage',q->>'audio_script',q->>'image_url',q->>'explanation',(q->>'sort_order')::int,q->'assessment_meta');
   FOR o IN SELECT value FROM jsonb_array_elements(q->'options') LOOP
    INSERT INTO quiz_options(id,question_id,option_text,is_correct,sort_order)
     VALUES((o->>'id')::uuid,(q->>'id')::uuid,o->>'option_text',(o->>'is_correct')::boolean,(o->>'sort_order')::int);
   END LOOP;
  END LOOP;
  UPDATE lessons SET assessment_policy=b->'policy',questions_per_attempt=(b->'policy'->>'questionsPerForm')::int,content=b->>'content'
   WHERE id=(b->>'lessonId')::uuid;
  UPDATE modules SET quiz_spec=coalesce(quiz_spec,'{}'::jsonb)||jsonb_build_object('total',(b->'policy'->>'questionsPerForm')::int,'version',b->>'version'),description=b->>'content'
   WHERE id=(b->>'moduleId')::uuid;
 END LOOP;
END $rotation$;
`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)) {
 const file=new URL('../migrations/195_final_exam_rotation.sql',import.meta.url),sql=buildRotationSql();
 if(process.argv.includes('--check')) {if(fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')!==sql)throw Error('Rotation migration drift');}
 else fs.writeFileSync(file,sql);
 console.log(JSON.stringify(rotationBanks.map(b=>({level:b.level,packages:2,perAttempt:b.policy.questionsPerForm,entries:b.rows.length}))));
}
