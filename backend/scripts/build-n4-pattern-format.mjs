import fs from 'node:fs';
import {fileURLToPath} from 'node:url';

const source = JSON.parse(fs.readFileSync(new URL('../content/n4-support/support-plan.json', import.meta.url), 'utf8'));
const tsv = fs.readFileSync(new URL('../content/n4-support/pattern-format.tsv', import.meta.url), 'utf8');

export function makePatternFormatPlan() {
  const counters = new Map();
  const rows = tsv.trim().split(/\r?\n/).slice(1).map(line => {
    const [chapterText, pattern, meaning, extra] = line.split('\t');
    const chapter = Number(chapterText);
    const index = counters.get(chapter) || 0;
    counters.set(chapter, index + 1);
    const original = source.grammar.filter(g => g.chapter === chapter)[index];
    if (!original || !pattern?.trim() || !meaning?.trim() || extra !== undefined) throw Error('Invalid row: ' + line);
    const module = source.chapters.find(m => m.id === original.expectedCore.module_id);
    const lesson = module.lessons.find(l => l.id === original.expectedCore.lesson_id);
    return {id: original.id, chapter, moduleId: module.id, moduleSlug: module.slug,
      lessonId: lesson.id, lessonSlug: lesson.slug,
      before: {pattern: original.expectedCore.pattern, meaning: original.expectedCore.meaning},
      after: {pattern, meaning}};
  });
  if (rows.length !== 125 || new Set(rows.map(r => r.id)).size !== 125 || counters.size !== 24) throw Error('Expected all 125 N4 cards in 24 chapters');
  return {courseId: source.courseId, rows};
}

export function patternFormatSql(plan = makePatternFormatPlan()) {
  return `-- N4 cards use N5's concise pattern / function / separate notes format.
-- Generated by backend/scripts/build-n4-pattern-format.mjs.
-- Only pattern and meaning change. IDs, notes, examples, dialogues, drills,
-- lesson/task memberships, media and student history remain untouched.
CREATE TABLE IF NOT EXISTS n4_pattern_format_backup_193 (
  grammar_id uuid PRIMARY KEY, course_id uuid NOT NULL,
  before_fields jsonb NOT NULL, after_fields jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
DO $format$
DECLARE
  p jsonb := $plan$${JSON.stringify(plan, null, 2)}$plan$::jsonb;
  r jsonb; actual jsonb; completed int;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:graph'));
  PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:' || (p->>'courseId')));
  SELECT count(*) INTO completed FROM n4_pattern_format_backup_193 WHERE course_id=(p->>'courseId')::uuid;
  IF completed = jsonb_array_length(p->'rows') THEN RETURN; END IF;
  IF completed <> 0 THEN RAISE EXCEPTION '193 incomplete backup; review before applying'; END IF;
  LOCK TABLE courses, modules, lessons, module_grammar IN SHARE ROW EXCLUSIVE MODE;
  IF NOT EXISTS (SELECT 1 FROM courses WHERE id=(p->>'courseId')::uuid AND slug='n4') THEN
    RAISE EXCEPTION '193 N4 course changed';
  END IF;
  -- Validate all rows before writing any. A teacher edit is never overwritten.
  FOR r IN SELECT value FROM jsonb_array_elements(p->'rows') LOOP
    SELECT jsonb_build_object('pattern',g.pattern,'meaning',g.meaning) INTO actual
      FROM module_grammar g JOIN modules m ON m.id=g.module_id JOIN lessons l ON l.id=g.lesson_id
      WHERE g.id=(r->>'id')::uuid AND m.id=(r->>'moduleId')::uuid
        AND m.course_id=(p->>'courseId')::uuid AND m.slug=r->>'moduleSlug'
        AND l.id=(r->>'lessonId')::uuid AND l.module_id=m.id AND l.slug=r->>'lessonSlug';
    IF actual IS NULL OR (actual IS DISTINCT FROM r->'before' AND actual IS DISTINCT FROM r->'after') THEN
      RAISE EXCEPTION '193 N4 card changed or missing: %',r->>'id';
    END IF;
  END LOOP;
  FOR r IN SELECT value FROM jsonb_array_elements(p->'rows') LOOP
    INSERT INTO n4_pattern_format_backup_193(grammar_id,course_id,before_fields,after_fields)
      SELECT g.id,(p->>'courseId')::uuid,jsonb_build_object('pattern',g.pattern,'meaning',g.meaning),r->'after'
      FROM module_grammar g WHERE g.id=(r->>'id')::uuid;
    UPDATE module_grammar SET pattern=r->'after'->>'pattern',meaning=r->'after'->>'meaning',updated_at=now()
      WHERE id=(r->>'id')::uuid
        AND (pattern IS DISTINCT FROM r->'after'->>'pattern' OR meaning IS DISTINCT FROM r->'after'->>'meaning');
  END LOOP;
END $format$;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(new URL('../migrations/193_n4_pattern_format.sql', import.meta.url), patternFormatSql());
  console.log('Generated N4 pattern format migration: 125 cards / 24 chapters');
}
