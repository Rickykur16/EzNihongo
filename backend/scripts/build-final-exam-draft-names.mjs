import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {banks} from '../content/final-exams/index.mjs';
import {scoredBanks} from '../content/final-exams/scoring.mjs';
import {nameFinalQuestion} from '../content/final-exams/names.mjs';
export function buildDraftNamesSql(){
 const fields=['question','audio_script','image_url','explanation','assessment_meta','options'];
 const select=q=>Object.fromEntries(fields.map(k=>[k,q[k]]));
 const edits=[...banks,...scoredBanks].flatMap(b=>b.rows.filter(q=>q.question_category==='listening').map(q=>({id:q.id,old:select(q),next:select(nameFinalQuestion(q))})));
 return `-- Generated by backend/scripts/build-final-exam-draft-names.mjs.
-- Correct names in unfinished attempts only; preserve answer IDs, saved answers,
-- form, scoring policy, revision, timestamps and all completed results.
DO $draft_names$
DECLARE edits jsonb := $payload$${JSON.stringify(edits)}$payload$::jsonb;
 attempt record; q jsonb; e jsonb; questions jsonb; updated_q jsonb; changed boolean; patched int := 0;
BEGIN
 LOCK TABLE quiz_attempts IN SHARE ROW EXCLUSIVE MODE;
 FOR attempt IN SELECT id,assessment_snapshot FROM quiz_attempts
  WHERE completed_at IS NULL AND superseded_at IS NULL
   AND assessment_snapshot->>'version' IN ('jlpt-final-n5-v1','jlpt-final-n4-v1','jlpt-final-n5-v2','jlpt-final-n4-v2')
 LOOP
  questions := '[]'::jsonb; changed := false;
  FOR q IN SELECT value FROM jsonb_array_elements(attempt.assessment_snapshot->'questions') LOOP
   IF q->>'question_category'<>'listening' OR q->'assessment_meta'->>'wordingVersion'='natural-names-v1' THEN
    questions := questions||jsonb_build_array(q); CONTINUE;
   END IF;
   SELECT value INTO e FROM jsonb_array_elements(edits) WHERE value->>'id'=q->>'id';
   IF e IS NULL OR NOT(q @> (e->'old')) THEN RAISE EXCEPTION '198 unknown/edited draft question %',q->>'id'; END IF;
   updated_q := q||((e->'next')-'options');
   updated_q := jsonb_set(updated_q,'{options}',(SELECT jsonb_agg(o.value||n.value ORDER BY o.ord)
    FROM jsonb_array_elements(q->'options') WITH ORDINALITY o(value,ord)
    JOIN jsonb_array_elements(e->'next'->'options') n(value) ON n.value->>'id'=o.value->>'id'));
   questions := questions||jsonb_build_array(updated_q); changed := true;
  END LOOP;
  IF changed THEN
   UPDATE quiz_attempts SET assessment_snapshot=jsonb_set(assessment_snapshot,'{questions}',questions) WHERE id=attempt.id;
   patched := patched+1;
  END IF;
 END LOOP;
 RAISE NOTICE '198 natural names: corrected % unfinished final exam attempts',patched;
END $draft_names$;
`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const file=new URL('../migrations/198_final_exam_draft_names.sql',import.meta.url),sql=buildDraftNamesSql();
 if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')!==sql)throw Error('Draft names migration drift');}
 else fs.writeFileSync(file,sql);
 console.log('Draft name correction ready');
}
