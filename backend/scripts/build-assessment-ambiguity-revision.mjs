import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {banks,bankRows,revisions} from '../content/assessments/jlpt/revised.mjs';
import {banks as oldBanks,bankRows as oldRows} from '../content/assessments/jlpt/index.mjs';
import {illustration as oldIllustration} from './build-jlpt-assessments.mjs';
export {banks};
const lit=x=>x==null?'NULL':`'${String(x).replaceAll("'","''")}'`;
const json=x=>`${lit(JSON.stringify(x))}::jsonb`;
export function illustration(chapter){
 let svg=oldIllustration(chapter);
 if(chapter===6)svg=svg.replaceAll('りょうり','おきゃくさんの りょうり');
 if(chapter===18)svg=svg.replaceAll('A：２キロ　 B：５キロ','あか：２キロ　 くろ：５キロ')
   .replace('rx="5" fill="#fff"','rx="5" fill="#db675c"').replace('rx="5" fill="#fff"','rx="5" fill="#384352"');
 return svg;
}
export function buildRollout(){
 let sql=`-- Generated by build-assessment-ambiguity-revision.mjs.
-- Immutable v3 rows/attempts; clone owner edits and voices, replace only 24 audited items.
CREATE TABLE IF NOT EXISTS n5_assessment_backup_175(lesson_id uuid PRIMARY KEY,before_data jsonb NOT NULL,created_at timestamptz NOT NULL DEFAULT now());
`;
 for(const bank of banks){
  const old=oldRows(oldBanks.find(b=>b.chapter===bank.chapter));
  sql+=`\nDO $revision$
DECLARE target uuid; matches int;
BEGIN
 SELECT count(*),(array_agg(l.id))[1] INTO matches,target FROM lessons l
 JOIN modules m ON m.id=l.module_id JOIN courses c ON c.id=m.course_id
 WHERE c.slug='n5' AND l.type='quiz' AND l.slug LIKE 'assignment-bab-${bank.chapter}-%'
 AND m.title ~* '^BAB\\s*${bank.chapter}\\s*[:：]';
 IF matches<>1 THEN RAISE EXCEPTION '175: missing/ambiguous Bab ${bank.chapter}'; END IF;
 IF EXISTS(SELECT 1 FROM n5_assessment_backup_175 WHERE lesson_id=target) THEN RETURN; END IF;
 PERFORM 1 FROM lessons WHERE id=target FOR UPDATE;
 IF (SELECT assessment_policy->>'version' FROM lessons WHERE id=target) IS DISTINCT FROM 'n5-assessment-v3'
 THEN RAISE EXCEPTION '175: expected v3 Bab ${bank.chapter}'; END IF;
 IF (SELECT count(*) FROM quiz_questions WHERE lesson_id=target AND assessment_meta->>'version'='n5-assessment-v3')<>24
 THEN RAISE EXCEPTION '175: expected 24 source rows Bab ${bank.chapter}'; END IF;
 INSERT INTO n5_assessment_backup_175(lesson_id,before_data)
 SELECT id,jsonb_build_object('assessment_policy',assessment_policy,'content',content,'questions_per_attempt',questions_per_attempt) FROM lessons WHERE id=target;
`;
  for(const [i,row] of bankRows(bank).entries()){
   const previous=old[i];
   sql+=` IF NOT EXISTS(SELECT 1 FROM quiz_questions WHERE id=${lit(previous.id)} AND lesson_id=target AND assessment_meta->>'version'='n5-assessment-v3') THEN RAISE EXCEPTION '175: missing source ${previous.assessment_meta.key}'; END IF;\n`;
   if(revisions.has(`${bank.chapter}:${i+1}`)){
    const fields=Object.keys(row).filter(k=>k!=='options');
    const vals=fields.map(k=>k==='assessment_meta'?`(q.assessment_meta-'ordered'-'starPosition'-'spokenChoices') || ${json(row[k])}`:typeof row[k]==='number'?row[k]:lit(row[k]));
    sql+=` INSERT INTO quiz_questions(lesson_id,${fields.join(',')},audio_scene,grammar_id)
 SELECT target,${vals.join(',')},q.audio_scene,q.grammar_id FROM quiz_questions q WHERE q.id=${lit(previous.id)};\n`;
    for(const o of row.options)sql+=` INSERT INTO quiz_options(id,question_id,option_text,is_correct,sort_order) VALUES(${lit(o.id)},${lit(row.id)},${lit(o.option_text)},${o.is_correct},${o.sort_order});\n`;
   }else{
    const fields=['question','question_type','question_category','grammar_id','section_number','section_label','section_instruction','audio_script','audio_scene','passage','image_url','correct_answer','explanation','sort_order'];
    sql+=` INSERT INTO quiz_questions(id,lesson_id,${fields.join(',')},assessment_meta)
 SELECT ${lit(row.id)},target,${fields.map(k=>'q.'+k).join(',')},q.assessment_meta || ${json({version:bank.version,key:row.assessment_meta.key})}
 FROM quiz_questions q WHERE q.id=${lit(previous.id)};
 INSERT INTO quiz_options(id,question_id,option_text,is_correct,image_url,sort_order)
 SELECT md5(id::text||':n5-assessment-v4')::uuid,${lit(row.id)},option_text,is_correct,image_url,sort_order FROM quiz_options WHERE question_id=${lit(previous.id)};
`;
   }
  }
  sql+=` IF EXISTS(SELECT 1 FROM quiz_questions q WHERE lesson_id=target AND assessment_meta->>'version'='n5-assessment-v4'
 AND ((SELECT count(*) FROM quiz_options o WHERE o.question_id=q.id) <> CASE WHEN q.assessment_meta->>'itemType' IN ('verbal_expression','quick_response') THEN 3 ELSE 4 END
 OR (SELECT count(*) FROM quiz_options o WHERE o.question_id=q.id AND o.is_correct)=0
 OR (SELECT count(*) FROM quiz_options o WHERE o.question_id=q.id AND o.is_correct)>1))
 THEN RAISE EXCEPTION '175: invalid choices Bab ${bank.chapter}'; END IF;
 UPDATE lessons SET assessment_policy=assessment_policy || ${json({version:bank.version})},updated_at=now() WHERE id=target;
END;
$revision$;
`;
 }
 return sql;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const target=new URL('../migrations/175_assessment_ambiguity_revision.sql',import.meta.url);
 const outputs=[[target,buildRollout()],...[6,18].map(c=>[new URL(`../../assets/assessments/b${c}-r2.svg`,import.meta.url),illustration(c)])];
 for(const [path,content] of outputs){
  if(process.argv.includes('--check')){if((await readFile(path,'utf8')).replaceAll('\r\n','\n')!==content)throw Error(`Generated drift: ${path}`);}
  else await writeFile(path,content);
 }
 console.log(`v4: ${banks.length} banks; ${revisions.size} editorial revisions; immutable v3 history.`);
}
