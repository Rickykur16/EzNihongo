import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {namedBanks} from '../content/final-exams/names.mjs';
import {curriculumBanks} from '../content/final-exams/curriculum.mjs';
const fields=['question','passage','audio_script','image_url','explanation','assessment_meta','options'];
const select=q=>Object.fromEntries(fields.map(k=>[k,q[k]]));
export function buildCurriculumSql(){
 const edits=curriculumBanks.flatMap((b,i)=>b.rows.flatMap((q,j)=>JSON.stringify(q)===JSON.stringify(namedBanks[i].rows[j])?[]:[{id:q.id,lessonId:b.lessonId,old:select(namedBanks[i].rows[j]),next:select(q)}]));
 return `-- Generated by backend/scripts/build-final-exam-curriculum.mjs.
-- Changed questions invalidate pending drafts; completed exam history is immutable.
DO $scope$
DECLARE edits jsonb := $payload$${JSON.stringify(edits)}$payload$::jsonb; e jsonb; o jsonb; current_row jsonb; changed boolean := false; reset_count int;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('curriculum-boundary:graph'));
 LOCK TABLE quiz_questions,quiz_options,quiz_attempts IN SHARE ROW EXCLUSIVE MODE;
 FOR e IN SELECT value FROM jsonb_array_elements(edits) LOOP
  SELECT jsonb_build_object('question',question,'passage',passage,'audio_script',audio_script,'image_url',image_url,'explanation',explanation,'assessment_meta',assessment_meta,'options',(SELECT jsonb_agg(jsonb_build_object('id',o.id,'option_text',o.option_text,'is_correct',o.is_correct,'sort_order',o.sort_order) ORDER BY o.sort_order) FROM quiz_options o WHERE o.question_id=quiz_questions.id))
  INTO current_row FROM quiz_questions WHERE id=(e->>'id')::uuid AND lesson_id=(e->>'lessonId')::uuid;
  IF current_row IS NULL THEN RAISE EXCEPTION '199 missing question %',e->>'id'; END IF;
  IF current_row->'assessment_meta'->>'scopeRevision'='curriculum-scope-v1' THEN CONTINUE; END IF;
  IF current_row IS DISTINCT FROM e->'old' THEN RAISE EXCEPTION '199 question edited; review required %',e->>'id'; END IF;
 END LOOP;
 FOR e IN SELECT value FROM jsonb_array_elements(edits) LOOP
  IF EXISTS(SELECT 1 FROM quiz_questions WHERE id=(e->>'id')::uuid AND assessment_meta->>'scopeRevision'='curriculum-scope-v1') THEN CONTINUE; END IF;
  FOR o IN SELECT value FROM jsonb_array_elements(e->'next'->'options') LOOP
   UPDATE quiz_options SET option_text=o->>'option_text' WHERE id=(o->>'id')::uuid AND question_id=(e->>'id')::uuid;
  END LOOP;
  UPDATE quiz_questions SET question=e->'next'->>'question',passage=e->'next'->>'passage',audio_script=e->'next'->>'audio_script',image_url=e->'next'->>'image_url',explanation=e->'next'->>'explanation',assessment_meta=e->'next'->'assessment_meta' WHERE id=(e->>'id')::uuid;
  changed := true;
 END LOOP;
 IF changed THEN
  UPDATE quiz_attempts SET superseded_at=clock_timestamp()
   WHERE completed_at IS NULL AND superseded_at IS NULL
    AND lesson_id IN (SELECT DISTINCT (value->>'lessonId')::uuid FROM jsonb_array_elements(edits))
    AND (assessment_snapshot->>'version' IN ('jlpt-final-n5-v1','jlpt-final-n4-v1') OR EXISTS(
     SELECT 1 FROM jsonb_array_elements(assessment_snapshot->'questions') q JOIN jsonb_array_elements(edits) entry ON q->>'id'=entry->>'id'
     WHERE q->'assessment_meta'->>'scopeRevision' IS DISTINCT FROM 'curriculum-scope-v1'));
  GET DIAGNOSTICS reset_count = ROW_COUNT;
  RAISE NOTICE '199 curriculum scope: superseded % unfinished final exams; completed results retained',reset_count;
 END IF;
END $scope$;
`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const path=new URL('../migrations/199_final_exam_curriculum_scope.sql',import.meta.url),sql=buildCurriculumSql();
 if(process.argv.includes('--check')){if(fs.readFileSync(path,'utf8').replaceAll('\r\n','\n')!==sql)throw Error('Scope migration drift');}else fs.writeFileSync(path,sql);
 console.log('Curriculum scope migration ready');
}
