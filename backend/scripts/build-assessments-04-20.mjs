import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {banks} from '../content/assessments/source/index.mjs';
import {validateBank} from './build-chapter-assessments.mjs';
import {CHAPTER_POLICY} from '../src/chapter-assessment.js';
export {banks};
const lit=v=>v==null?'NULL':`'${String(v).replaceAll("'","''")}'`;
const json=v=>`${lit(JSON.stringify(v))}::jsonb`;
export function buildRollout() {
  if (banks.length!==17 || banks.some((b,i)=>b.chapter!==i+4)) throw Error('Expected Bab 4–20');
  let sql=`-- Generated by build-assessments-04-20.mjs. All 24 reviewed items appear on every attempt.
-- Preserve legacy questions, current attempts, audio infrastructure and completion history.
CREATE TABLE IF NOT EXISTS n5_assessment_backup_171 (
  lesson_id UUID PRIMARY KEY, before_data JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
`;
  for(const bank of banks) {
    const rows=validateBank(bank);
    const policy={version:bank.version,chapter:bank.chapter,title:bank.title,selection:'all',objectives:bank.objectives,boundary:bank.boundary,transferTask:bank.transferTask,...CHAPTER_POLICY};
    const content='24 soal pilihan ganda; seluruh soal ditampilkan setiap pengerjaan: 6 aksara dan kosakata, 10 tata bahasa, 4 membaca, dan 4 listening. Materi dibatasi sampai bab ini. Lulus dengan nilai total minimal 70%, tiap kategori minimal 50%, dan sekurangnya satu jawaban benar pada setiap tujuan. Jawaban dapat disimpan dan dilanjutkan. Pembahasan dan transkrip tersedia setelah semua jawaban dikirim. Siapkan audio.';
    sql+=`\nDO $rollout$
DECLARE target UUID; matches INT; scene JSONB;
BEGIN
 SELECT count(*),(array_agg(l.id))[1] INTO matches,target FROM lessons l
 JOIN modules m ON m.id=l.module_id JOIN courses c ON c.id=m.course_id
 WHERE c.slug='n5' AND l.type='quiz' AND l.slug LIKE 'assignment-bab-${bank.chapter}-%'
 AND m.title ~* '^BAB\\s*${bank.chapter}\\s*[:：]';
 IF matches<>1 THEN RAISE EXCEPTION '171: missing/ambiguous Bab ${bank.chapter} assignment'; END IF;
 IF EXISTS(SELECT 1 FROM n5_assessment_backup_171 WHERE lesson_id=target) THEN RETURN; END IF;
 INSERT INTO n5_assessment_backup_171(lesson_id,before_data)
 SELECT id,jsonb_build_object('assessment_policy',assessment_policy,'content',content,'questions_per_attempt',questions_per_attempt) FROM lessons WHERE id=target;
 -- Reuse saved dialogue character voices when configured. Anonymous A/B
 -- scripts otherwise retain the existing explicit female/male TTS defaults;
 -- the admin's existing listening-scene editor can override each character.
 SELECT jsonb_build_object('schemaVersion',1,'enabled',true,'backgroundKey','classroom',
 'participants',jsonb_agg(jsonb_build_object('characterKey',s.character_key,
 'position',CASE WHEN s.character_key='anna-wijaya' THEN 'left' ELSE 'right' END,
 'speaker',CASE WHEN s.character_key='anna-wijaya' THEN 'A' ELSE 'B' END,
 'displayName',CASE WHEN s.character_key='anna-wijaya' THEN 'Pembicara A' ELSE 'Pembicara B' END,
 'voiceId',s.voice_id,'voiceName',COALESCE(s.voice_name,''),'profileVersion',s.profile_version,'custom',false) ORDER BY s.character_key))
 INTO scene FROM dialogue_speakers s WHERE s.character_key IN ('anna-wijaya','hadi-pratama')
 AND NULLIF(s.voice_id,'') IS NOT NULL HAVING count(*)=2;
`;
    for(const q of rows) {
      const fields=['id','question','question_type','question_category','section_number','section_label','section_instruction','passage','audio_script','explanation','sort_order','assessment_meta'];
      sql+=` INSERT INTO quiz_questions(lesson_id,${fields.join(',')},audio_scene) VALUES(target,${fields.map(k=>k==='assessment_meta'?json(q[k]):typeof q[k]==='number'?q[k]:lit(q[k])).join(',')},${q.audio_script?'scene':'NULL'});\n`;
      for(const o of q.options) sql+=` INSERT INTO quiz_options(id,question_id,option_text,is_correct,sort_order) VALUES(${lit(o.id)},${lit(q.id)},${lit(o.option_text)},${o.is_correct},${o.sort_order});\n`;
    }
    sql+=` UPDATE lessons SET assessment_policy=${json(policy)},content=${lit(content)},questions_per_attempt=24,updated_at=NOW() WHERE id=target;
END;
$rollout$;
`;
  }
  return sql;
}
if(process.argv[1]===fileURLToPath(import.meta.url)) {
  const target=new URL('../migrations/171_rebuild_n5_assessments_04_20.sql',import.meta.url);
  const sql=buildRollout();
  if(process.argv.includes('--check')) {
    if((await readFile(target,'utf8')).replaceAll('\r\n','\n')!==sql)throw Error('Regenerate migration 171');
  } else await writeFile(target,sql);
  console.log('Validated 17 banks: 408 choice items, including 68 independent listening stimuli.');
}
