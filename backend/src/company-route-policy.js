const rules = LEGACY_ROUTES.map(([method, path, permission]) => ({ method, permission,
  pattern: new RegExp('^' + path.split('/').map(part => part.startsWith(':') ? '[^/]+' : part).join('/') + '/?$') }));
export function permissionForLegacyRoute(method, path) {
  // Express automatically handles HEAD for GET. Authorization must agree.
  return rules.find(rule => rule.method === (method === 'HEAD' ? 'GET' : method) && rule.pattern.test(path))?.permission || null;
}
